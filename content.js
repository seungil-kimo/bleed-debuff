// ── 날짜별로 섞어서 고르기 ──
// 같은 날에는 두 폰에 같은 내용, 다음 날이면 다른 내용. 주기마다 순서도 새로 섞여요.
function hash(str) { let h = 2166136261; for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
function rng(seed) { return () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }
function shuffled(arr, seedStr) { const a = arr.slice(), r = rng(hash(seedStr)); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }

// arr에서 n개를 고름. cycleKey: 주기마다 다른 순서, dayIdx: 날마다 다음 묶음
export function pick(arr, n, cycleKey, dayIdx, tag) {
 if (!arr || !arr.length) return [];
 const a = shuffled(arr, cycleKey + '|' + tag), out = [];
 const k = Math.min(n, a.length);
 for (let i = 0; i < k; i++) out.push(a[(dayIdx * k + i) % a.length]);
 return out;
}
